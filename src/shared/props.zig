pub const max_local = 256;

pub const kind_capacity = named_kinds + max_local;

pub var local: []const Info = &.{};

pub fn localKind(i: usize) Kind {
    return @enumFromInt(named_kinds + i);
}

pub fn isNamed(kind: Kind) bool {
    return @intFromEnum(kind) < named_kinds;
}

pub fn name(kind: Kind) []const u8 {
    if (isNamed(kind)) return @tagName(kind);

    const i = @intFromEnum(kind) - named_kinds;

    return if (i < local.len) local[i].file else "";
}

pub fn valid(kind: Kind) bool {
    const i = @intFromEnum(kind);

    return i < named_kinds or i - named_kinds < local.len;
}

pub fn info(kind: Kind) Info {
    const i = @intFromEnum(kind);

    if (i < named_kinds) return infos[i];

    return local[i - named_kinds];
}
